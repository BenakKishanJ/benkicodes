/** Merge horizontal runs of the same char into <rect> strings. */
export function spriteRects(rows: string[]): string {
  let out = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      if (c === '.') { x++; continue; }
      let n = 1;
      while (row[x + n] === c) n++;
      out += `<rect x="${x}" y="${y}" width="${n}" height="1"${c === '+' ? ' fill-opacity=".5"' : ''}/>`;
      x += n;
    }
  });
  return out;
}
